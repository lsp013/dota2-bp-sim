#!/usr/bin/env node
/**
 * Generate src/heroPinyin.mjs — pinyin for every hero, so the hero pool can be
 * searched as `difashi`, `dfs`, `binghun` or `bh`.
 *
 *   node scripts/gen-pinyin.mjs
 *
 * WHY A GENERATED TABLE
 * ---------------------
 * The site has no runtime dependencies and CI installs nothing, so a pinyin
 * library cannot be shipped or run during the workflow. This runs occasionally,
 * by hand, and commits the result — the same pattern as src/heroNames.mjs.
 * tests/heroNames.test.mjs fails if a hero has no pinyin, so a newly released
 * hero cannot silently become unsearchable by pinyin.
 *
 * WHAT IS INDEXED
 * ---------------
 *   - the official Chinese name  (水晶室女 -> shuijingshinv / sjsn)
 *   - every Chinese NICKNAME     (冰魂 -> binghun / bh)
 * Latin nicknames (NEC, AM, KOTL) need no pinyin and are skipped.
 *
 * TWO TRAPS THIS HANDLES
 * ----------------------
 *   - 女 is nǚ, and pinyin-pro writes `ü`. That is non-ASCII, so a query could
 *     never contain it: 水晶室女 was unreachable by pinyin entirely. Every
 *     string is emitted twice where needed, with ü written as `v` (the typing
 *     convention: nv) AND as `u` (what people also type).
 *   - polyphones need context, which is why a word-aware library is used rather
 *     than a character-by-character table: 行 in 风行者 is xíng, not háng.
 *
 * HOW TO REFRESH
 * --------------
 *   curl -L https://registry.npmjs.org/pinyin-pro/-/pinyin-pro-<ver>.tgz -o tmp/pinyin/pkg.tgz
 *   tar -xzf tmp/pinyin/pkg.tgz -C tmp/pinyin
 *   node scripts/gen-pinyin.mjs
 */

import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { HERO_ZH, HERO_NICKNAMES } from '../src/heroNames.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const LIB = resolve(ROOT, 'tmp/pinyin/package/dist/index.js');
const OUT = resolve(ROOT, 'src/heroPinyin.mjs');

const CJK = /[\u3400-\u9fff]/;
const require = createRequire(import.meta.url);

function loadPinyin() {
  try {
    return require(LIB).pinyin;
  } catch (err) {
    throw new Error(
      `读不到 pinyin-pro（${LIB}）：${err.message}\n` +
        '先按文件头的 HOW TO REFRESH 解包，再运行本脚本。'
    );
  }
}

/**
 * ü is not typeable on most keyboards, so it is written `v` by convention and
 * often simply `u`. Emitting both keeps those heroes reachable.
 */
function asciiVariants(s) {
  const out = new Set([s.replace(/ü/g, 'v'), s.replace(/ü/g, 'u')]);
  return [...out];
}

async function main() {
  const pinyin = loadPinyin();
  const ds = JSON.parse(await readFile(resolve(ROOT, 'public/data/data.json'), 'utf8'));

  const rows = [];
  let nicknameCount = 0;
  let foldedCount = 0;

  for (const hero of ds.heroes) {
    const zh = hero.zh ?? HERO_ZH[hero.id];
    if (!zh) continue;

    // The official name, then every Chinese nickname.
    const spellings = [zh];
    for (const nick of HERO_NICKNAMES[hero.id] ?? []) {
      if (CJK.test(nick)) {
        spellings.push(nick);
        nicknameCount++;
      }
    }

    const full = new Set();
    const initials = new Set();

    for (const text of spellings) {
      const syllables = pinyin(text, { toneType: 'none', type: 'array' });
      const firsts = pinyin(text, { pattern: 'first', toneType: 'none', type: 'array' });
      const joined = syllables.join('');
      if (joined !== joined.replace(/ü/g, 'v')) foldedCount++;
      for (const v of asciiVariants(joined)) full.add(v);
      initials.add(firsts.join(''));
    }

    rows.push({
      id: hero.id,
      zh,
      full: [...full],
      initials: [...initials],
    });
  }

  rows.sort((a, b) => a.id - b.id);

  const body = rows
    .map((r) => {
      const f = r.full.map((x) => `'${x}'`).join(', ');
      const i = r.initials.map((x) => `'${x}'`).join(', ');
      return `  ${r.id}: { f: [${f}], i: [${i}] },`;
    })
    .join('\n');

  const file = `/**
 * Pinyin for every hero, keyed by hero id. GENERATED by scripts/gen-pinyin.mjs
 * — do NOT hand-edit.
 *
 *   f: full pinyin, matched as a SUBSTRING (so 'bingpo' finds 远古冰魄)
 *   i: initials, matched as a PREFIX (so 'df' and 'dfs' find 敌法师)
 *
 * Covers the official Chinese name and every Chinese nickname:
 *
 *   敌法师   ->  f: difashi          i: dfs
 *   远古冰魄 ->  f: yuangubingpo     i: ygbp
 *   风行者   ->  f: fengxingzhe      i: fxz     (行 is xíng, not háng)
 *   (冰魂 nickname) f: binghun       i: bh
 *
 * 女 is nǚ: those entries appear twice, with ü written both \`v\` (the typing
 * convention) and \`u\`, because ü is not typeable and an un-folded ü silently
 * made 水晶室女 unreachable by pinyin.
 *
 * Committed rather than computed at build time: the site has no runtime
 * dependencies and CI installs nothing. Regenerate after adding a hero or a
 * nickname; tests/heroNames.test.mjs fails until you do.
 */
export const HERO_PINYIN = {
${body}
};

export default HERO_PINYIN;
`;

  await writeFile(OUT, file, 'utf8');

  console.log(`写出 ${OUT}`);
  console.log(`  ${rows.length}/${ds.heroes.length} 个英雄`);
  console.log(`  中文外号也索引了 ${nicknameCount} 条`);
  console.log(`  因 ü 做了 ASCII 变形的 ${foldedCount} 条`);

  const nonAscii = rows.flatMap((r) =>
    [...r.full, ...r.initials].filter((s) => !/^[a-z0-9]+$/.test(s)).map((s) => `${r.zh}: ${s}`)
  );
  console.log(`  仍含非 ASCII 的: ${nonAscii.length}${nonAscii.length ? ' -> ' + nonAscii.join(', ') : ''}`);

  const show = (en) => {
    const h = ds.heroes.find((x) => x.n === en);
    const r = rows.find((x) => x.id === h?.id);
    return r ? `${r.zh} -> ${r.full.join(' | ')}  /  ${r.initials.join(' | ')}` : `${en} 未找到`;
  };
  console.log('\n抽查:');
  for (const en of ['Crystal Maiden', 'Ancient Apparition', 'Windranger', 'Muerta', 'Anti-Mage']) {
    console.log('  ' + show(en));
  }
}

main().catch((err) => {
  console.error('fatal:', err.message);
  process.exit(1);
});
